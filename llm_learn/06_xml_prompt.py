# 自动判分：机械地检查三条硬性要求
# ============================================================
def grade(text):
    """返回 (条目数, 最长条目字数, 带标注的条数, 是否全部通过)

    ⚠️ 最后一项是【精确度】，不只是【有没有】：
       5 条反馈里，只有「反馈 1」（身高适用范围）在说明书里查不到依据。
       所以正确结果是【恰好 1 条】带标注。
       如果标了 2 条以上 → 说明它对有依据的条目也乱标（过度标注）。
       如果 0 条 → 说明它漏了（该标没标）。
    """
    lines = [l.strip() for l in text.splitlines() if l.strip()]

    # 找"分点"的行：以 1. / 1、 / 1) / - / * 开头
    bullets = [l for l in lines if re.match(r"^(\d+[.、)]|[-*·])\s*", l)]
    n = len(bullets)
    longest = max((len(l) for l in bullets), default=0)

    flag_words = ("需进一步确认", "进一步确认", "待确认", "需确认", "暂无法确认", "无法确认")
    flagged = [l for l in bullets if any(w in l for w in flag_words)]

    ok = (n == 5) and (longest <= 40) and (len(flagged) == 1)
    return n, longest, len(flagged), ok


def section(title, prompt, do_grade=True):
    print("\n" + "=" * 64)
    print(f"【{title}】")
    print("=" * 64)

    text = stream_chat([{"role": "user", "content": prompt}])

    if do_grade:
        n, longest, n_flag, ok = grade(text)
        print("-" * 64)
        print(f"判分：条目数 {n}（期望 5）{'  ✅' if n == 5 else '  ❌'}")
        print(f"      最长条目 {longest} 字（期望 ≤ 40）{'  ✅' if longest <= 40 else '  ❌'}")
        print(f"      「需进一步确认」标注 {n_flag} 条（期望恰好 1）"
              f"{'  ✅' if n_flag == 1 else '  ❌'}")
        if n_flag > 1:
            print("         ↑ 过度标注：有依据的条目也被标上了")
        elif n_flag == 0:
            print("         ↑ 漏标：该标的那条没标")
        print(f"      → 总判定：{'✅ 全部通过' if ok else '❌ 有未通过项'}")
    return text


